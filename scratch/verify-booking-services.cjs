const assert = require('node:assert/strict');
const { priceBookingExtras } = require('../apps/api/dist/modules/bookings/booking-extras');
const { BookingsService } = require('../apps/api/dist/modules/bookings/bookings.service');
const { PaymentController } = require('../apps/api/dist/modules/payment/payment.controller');
(async () => {
  assert.equal(priceBookingExtras(['private_guide','travel_insurance','photography'], 2).total,600000);
  assert.equal(priceBookingExtras([],2).total,0);
  assert.throws(() => priceBookingExtras(['photography','photography'],2));
  assert.throws(() => priceBookingExtras(['guide'],2));
  const schedule = { status:1, quota:20, booked_count:0, price:790000, start_date:new Date(), tours:{name:'Test',status:1}, tour_schedule_prices:[{passenger_type:'ADULT',price:790000}], tour_schedule_hotels:[{nights:1,hotel_room_types:{base_price:100000}}] };
  let saved;
  const tx = { tour_schedules:{findUnique:async()=>schedule,updateMany:async()=>({count:1})},bookings:{create:async({data})=>{saved=data;return {...data,booking_id:1};}},booking_travelers:{createMany:async()=>{}},vouchers:{} };
  const db = {$transaction:async fn=>fn(tx),users:{findUnique:async()=>({user_id:7})}};
  const service = new BookingsService(db,{sendBookingCreatedEmail:async()=>{}});
  const dto={tour_schedule_id:1,contact_name:'Test',contact_phone:'0900000000',contact_email:'test@example.com',adult_count:2,child_count:0,infant_count:0,travelers:[],payment_method:'vnpay',single_room_count:1,room_type:'single',single_room_surcharge:1,additional_service_ids:['private_guide','photography'],services_total:1};
  await service.createForAccount(10,dto);
  assert.equal(saved.user_id,7); assert.equal(saved.services_total,500000);
  assert.equal(saved.total_amount,2180000); assert.equal(saved.additional_services.length,2);
  await assert.rejects(()=>service.createForAccount(10,{...dto,adult_count:-1}));
  await assert.rejects(()=>service.createForAccount(10,{...dto,travelers:[{fullName:'Test',type:'adult',gender:'male',birthday:'2001-02-29'}]}));
  tx.tour_schedules.updateMany=async()=>({count:0});
  await assert.rejects(()=>service.createForAccount(10,dto));
  let signedAmount;
  const payment = new PaymentController({createPaymentUrl:async(id,amount)=>{signedAmount=amount;return {paymentUrl:'test'};}}, {users:{findUnique:async()=>({user_id:7})},bookings:{findFirst:async()=>({booking_id:1,status:'pending',total_amount:2180000})}});
  await payment.create({bookingId:1,amount:1},{user:{accountId:10},ip:'127.0.0.1'});
  assert.equal(signedAmount,2180000);
  console.log('Passed: extras, guest/group prices, snapshots, server totals, invalid dates/counts, capacity conflict and payment amount.');
})().catch(error=>{console.error(error);process.exitCode=1});
